#!/usr/bin/env python3
"""
scripts/generate_phase_pages.py

Generates one lightweight overview page per phase under
website/docs/phases/<id>/index.md. These pages give search engines and
readers a stable entry point for each of the 20 phases (the sitemap
includes them) and link to every lesson in the phase.

The source of truth is curriculum.json. Existing files are only
overwritten when they carry the generated marker, so hand-written
content is never destroyed.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
CURRICULUM_PATH = ROOT / "curriculum.json"
PHASES_DIR = ROOT / "website" / "docs" / "phases"
MARKER = "<!-- generated by scripts/generate_phase_pages.py -->"


def short_description(value: str, limit: int = 158) -> str:
    text = re.sub(r"\s+", " ", value or "").strip()
    if len(text) <= limit:
        return text
    cut = text[:limit]
    space = cut.rfind(" ")
    if space > limit * 0.6:
        cut = cut[:space]
    return cut.rstrip("،,.؛;: ") + "…"


def escape_frontmatter(value: str) -> str:
    return str(value or "").replace("\\", "\\\\").replace('"', '\\"')


def escape_markdown_link_text(value: str) -> str:
    return str(value or "").replace("[", "\\[").replace("]", "\\]")


def build_page(phase: dict[str, Any]) -> str:
    phase_id = str(phase.get("id", "")).zfill(2)
    name_ar = str(phase.get("nameAr") or phase.get("name") or "").strip()
    description = str(phase.get("descriptionAr") or phase.get("description") or "").strip()
    lessons = phase.get("lessons", []) or []

    lines: list[str] = [
        "---",
        f'title: "المرحلة {phase_id} — {escape_frontmatter(name_ar)}"',
        f'description: "{escape_frontmatter(short_description(description))}"',
        "sidebar: false",
        "search: false",
        "---",
        "",
        MARKER,
        f"# المرحلة {phase_id}: {name_ar}",
        "",
    ]

    if description:
        lines += [description, ""]

    lines += [
        f"هذه الصفحة تجمع دروس المرحلة ({len(lessons)} درسًا) في مكان واحد. "
        "ابدأ بالدرس الأول ثم تابع بالترتيب، أو ارجع إلى خريطة المسار لاختيار مسار مختلف.",
        "",
        "## دروس المرحلة",
        "",
    ]

    for lesson in lessons:
        lesson_id = str(lesson.get("id", "")).zfill(2)
        title_ar = str(lesson.get("titleAr") or lesson.get("title") or "").strip()
        title_en = str(lesson.get("title") or "").strip()
        slug = str(lesson.get("slug") or "").strip()
        if not slug:
            continue
        link = f"/phases/{phase_id}/{slug}"
        label = escape_markdown_link_text(title_ar)
        suffix = f" — {title_en}" if title_en and title_en != title_ar else ""
        lines.append(f"{lesson_id}. [{label}]({link}){suffix}")

    lines += [
        "",
        "---",
        "",
        f"[← العودة إلى خريطة المسار](/roadmap) · [المرحلة التالية →](/phases/{int(phase_id) + 1:02d}/)"
        if int(phase_id) < 19
        else "[← العودة إلى خريطة المسار](/roadmap)",
        "",
    ]

    return "\n".join(lines)


def main() -> int:
    if not CURRICULUM_PATH.exists():
        print(f"ERROR: missing curriculum: {CURRICULUM_PATH}")
        return 1

    curriculum = json.loads(CURRICULUM_PATH.read_text(encoding="utf-8"))
    phases = curriculum.get("phases", [])
    if not phases:
        print("ERROR: curriculum.json has no phases")
        return 1

    created = 0
    updated = 0
    skipped = 0

    for phase in phases:
        phase_id = str(phase.get("id", "")).zfill(2)
        target = PHASES_DIR / phase_id / "index.md"
        content = build_page(phase)

        if target.exists():
            current = target.read_text(encoding="utf-8")
            if MARKER not in current:
                print(f"SKIP (hand-written): {target}")
                skipped += 1
                continue
            if current == content:
                skipped += 1
                continue
            target.write_text(content, encoding="utf-8", newline="\n")
            updated += 1
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
            created += 1

    print(
        f"Phase pages: {created} created, {updated} updated, "
        f"{skipped} unchanged/skipped -> {PHASES_DIR}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
